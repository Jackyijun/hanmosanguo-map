"""郡国、城邑与分区种子。
Z = 东汉郡国治所（t=z）；C = 城邑（t=c）；R = 仅参与分区（t=r）。
j：郡国所属的州（Z）或城邑所属的郡（C/R）；部族分区种子的 j 为部族组名。
R：分区半径上限（度），缺省 z 2.6 / c 1.6 / r 2.2。
"""
SEEDS = []

def Z(n, zh, lon, lat, mod, note="", nm=None, R=None, id=None):
    SEEDS.append(dict(id=id or n, n=n, t="z", j=zh, lon=lon, lat=lat, mod=mod, note=note, nm=nm, R=R))

def C(n, jun, lon, lat, mod, note="", nm=None, R=None, id=None):
    SEEDS.append(dict(id=id or n, n=n, t="c", j=jun, lon=lon, lat=lat, mod=mod, note=note, nm=nm, R=R))

def R(id, jun, lon, lat, R=None, n=None, mod=""):
    SEEDS.append(dict(id=id, n=n or id, t="r", j=jun, lon=lon, lat=lat, mod=mod, note="", nm=None, R=R))

